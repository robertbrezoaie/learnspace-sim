"""Generates RESULTS.md: one section per RQ, every number with its CI and its paper_numbers.json key, and caption drafts.

Nothing in this file is a hand-written number: every value is read from the flat numbers dictionary.
"""
from __future__ import annotations

from common import QUICK, SUMMARY, SYNTHETIC_NOTE


class Numbers:
    def __init__(self, flat: dict):
        self.flat = flat

    def has(self, key: str) -> bool:
        return f"{key}.mean" in self.flat or key in self.flat

    def v(self, key: str, d: int = 3, pct: bool = False) -> str:
        """Value with CI and key: '0.913 [0.905, 0.921] (`key`)'."""
        f = self.flat
        scale = 100 if pct else 1
        unit = "%" if pct else ""
        if f"{key}.mean" in f:
            m, lo, hi = f.get(f"{key}.mean"), f.get(f"{key}.ci_low"), f.get(f"{key}.ci_high")
            if m is None:
                return f"n/a (`{key}`)"
            s = f"{m * scale:.{d}f}{unit}"
            if lo is not None and hi is not None:
                s += f" [{lo * scale:.{d}f}, {hi * scale:.{d}f}]"
            return f"{s} (`{key}`)"
        val = f.get(key)
        if isinstance(val, float):
            return f"{val * scale:.{d}f}{unit} (`{key}`)"
        return f"{val} (`{key}`)"

    def raw(self, key: str):
        return self.flat.get(key)


def yesno(x) -> str:
    return {True: "**holds**", False: "**does not hold**", None: "not evaluable"}[x]


def write(num: dict, flat: dict, figs: list[dict], tabs: list[tuple[str, str]]) -> None:
    n = Numbers(flat)
    L: list[str] = []
    add = L.append
    add("# RESULTS — LearnSpace simulation study")
    add("")
    add(f"> **{SYNTHETIC_NOTE}**")
    add("")
    add("This file is generated by `analysis/make_all.py`. Every number below comes from `results/summary/paper_numbers.json`; "
        "the key is given in backticks. Values are means over runs with 95% t-intervals in brackets (field replica: Wilson 95% intervals). "
        "Differences are seed-paired (common random numbers).")
    if QUICK:
        add("")
        add("> **QUICK RUN (N = 100, 3 seeds): for development only, never for the paper.**")
    add("")

    # ---------- K1-K4 ----------
    if "k" in num:
        add("## Pre-registered expected results (K1–K4)")
        add("")
        add("| ID | Expected result | Estimate (seed-paired difference) | Outcome |")
        add("|---|---|---|---|")
        k = num["k"]
        add(f"| K1 | {k['K1']['statement']} | v2 − v1 = {n.v('k.K1.estimate')} | {yesno(k['K1']['holds'])} |")
        add(f"| K2 | {k['K2']['statement']} | tie 0.2 − tie 0 = {n.v('k.K2.estimate')} | {yesno(k['K2']['holds'])} |")
        add(f"| K3 | {k['K3']['statement']} | S1: {n.v('k.K3.estimate_S1', 1)}; S2: {n.v('k.K3.estimate_S2', 1)} | {yesno(k['K3']['holds'])} |")
        add(f"| K4 | {k['K4']['statement']} | C4 − C3 = {n.v('k.K4.estimate')} | {yesno(k['K4']['holds'])} |")
        add("")
        add("Results that contradict an expected result are reported as they are (PREREGISTRATION.md, section 8).")
        add("")

    # ---------- RQ1 ----------
    if "x1" in num:
        add("## RQ1 — Decision-specific explanations")
        add("")
        add(f"Audit sample: {n.v('x1.n_runs')} runs (EXP-P cells C2 and B-TS, scenario S2, seeds 1–5). "
            f"Explained reward decisions audited: {n.v('x1.reward.v2.n_decisions')}; explained difficulty decisions: {n.v('x1.difficulty.v2.n_decisions')}.")
        add("")
        add("### X1 — Rule comparison")
        add("")
        add("Reward decisions (three inputs):")
        add("")
        for rule in ["v1", "v2", "random"]:
            add(f"- {rule}: DN {n.v(f'x1.reward.{rule}.DN')}; SU {n.v(f'x1.reward.{rule}.SU')}; SI {n.v(f'x1.reward.{rule}.SI')}; NC {n.v(f'x1.reward.{rule}.NC')}")
        add(f"- DN, v2 − v1: {n.v('x1.reward.diff.v2_minus_v1.DN')}; SU, v2 − v1: {n.v('x1.reward.diff.v2_minus_v1.SU')}")
        add(f"- Agreement of the v1 and v2 primary factor (AGR): {n.v('x1.reward.v1.AGR')}")
        add("")
        add("Difficulty decisions (single input e; v2 is correct by construction, so the comparison is NC and AGR):")
        add("")
        add(f"- v1 names a non-contributing factor (NC): {n.v('x1.difficulty.v1.NC')}")
        add(f"- v1 agrees with v2 (AGR): {n.v('x1.difficulty.v1.AGR')}")
        add(f"- v1 deletion necessity (DN): {n.v('x1.difficulty.v1.DN')}; v2 DN: {n.v('x1.difficulty.v2.DN')}")
        add("")
        add("### X2 — Stability under input noise (reward decisions)")
        add("")
        add("| sigma_n | delta_tie = 0 | delta_tie = 0.1 | delta_tie = 0.2 | delta_tie = 0.3 |")
        add("|---|---|---|---|---|")
        for sd in ["0.05", "0.1", "0.2"]:
            cells = [n.v(f"x2.reward.sd{sd}.tie{t}.ST_exact") for t in ["0", "0.1", "0.2", "0.3"]]
            add(f"| {sd} | " + " | ".join(cells) + " |")
        add("")
        add(f"- ST_exact difference, delta_tie 0.2 − 0, at sigma_n = 0.10: {n.v('x2.reward.sd0.1.diff_tie0.2_minus_tie0.ST_exact')}")
        add(f"- ST_jaccard difference, delta_tie 0.2 − 0, at sigma_n = 0.10: {n.v('x2.reward.sd0.1.diff_tie0.2_minus_tie0.ST_jaccard')}")
        add(f"- Two-factor rate TF: delta_tie 0.1 {n.v('x2.reward.TF_by_tie.tie0.1')}; 0.2 {n.v('x2.reward.TF_by_tie.tie0.2')}; 0.3 {n.v('x2.reward.TF_by_tie.tie0.3')}")
        add(f"- Difficulty decisions: share of noise draws that change the decision category at sigma_n = 0.10: {n.v('x2.difficulty.sd0.1.category_change_share')}")
        add("")
        add("### X3 — Reward weight sweep (appendix)")
        add("")
        add(f"- At the default weights (delta_tie = 0.2): TF {n.v('x3.tie0.2.default.TF')}, ST_exact {n.v('x3.tie0.2.default.ST_exact')}, "
            f"DN {n.v('x3.tie0.2.default.DN')}, XR {n.v('x3.tie0.2.default.XR')}")
        add(f"- Over the {n.v('x3.tie0.2.n_points')} weight points: TF from {n.v('x3.tie0.2.grid_min.TF')} to {n.v('x3.tie0.2.grid_max.TF')}; "
            f"ST_exact from {n.v('x3.tie0.2.grid_min.ST_exact')} to {n.v('x3.tie0.2.grid_max.ST_exact')}")
        add("")
        add("### X4 — Exposure")
        add("")
        add(f"- v2 reward explanations per attended session: {n.v('x4.reward.per_session_mean', 2)}; difficulty explanations: {n.v('x4.difficulty.per_session_mean', 2)}")
        add("")
        add("### X5 — Example cases")
        add("")
        add("Three real cases chosen by fixed rules are in `results/summary/example_cases.json` (they replace the illustrative example of the paper's section 3.5).")
        add("")
        add(f"Difficulty decisions suppressed by the clip (excluded from all rules): C2 {n.v('explain_counts.C2.suppressed_by_clip')}; B-TS {n.v('explain_counts.B-TS.suppressed_by_clip')} task rows.")
        add("")

    # ---------- RQ2 ----------
    if "bandit" in num:
        add("## RQ2 — Feedback bandit")
        add("")
        add("Final cumulative regret against the best fixed arm (REG_fixed) and policy value (VAL), EXP-P (N = 500, 20 sessions):")
        add("")
        add("| Scenario | TS_DEPLOYED REG_fixed | RANDOM REG_fixed | TS − RANDOM | TS_DEPLOYED VAL | ORACLE VAL |")
        add("|---|---|---|---|---|---|")
        for sc in ["S0", "S1", "S2", "S3"]:
            if f"bandit.{sc}.B-TS.REG_fixed.mean" not in flat:
                continue
            add(f"| {sc} | {n.v(f'bandit.{sc}.B-TS.REG_fixed', 1)} | {n.v(f'bandit.{sc}.B-RANDOM.REG_fixed', 1)} | "
                f"{n.v(f'bandit.{sc}.diff.TS_minus_RANDOM.REG_fixed', 1)} | {n.v(f'bandit.{sc}.B-TS.VAL')} | {n.v(f'bandit.{sc}.B-ORACLE.VAL')} |")
        add("")
        for sc in ["S1", "S2"]:
            if f"bandit.{sc}.B-TS.T95_reached_share" in flat:
                add(f"- {sc}: TS_DEPLOYED reaches P_best ≥ 0.95 for the best fixed arm in {n.v(f'bandit.{sc}.B-TS.T95_reached_share')} of runs; "
                    f"median decision index when reached {n.v(f'bandit.{sc}.B-TS.T95_median_if_reached', 0)}. Best fixed arm: {n.v(f'bandit.{sc}.best_fixed_arm')}.")
        add(f"- S2, TS_CTX − TS_DEPLOYED (descriptive): REG_oracle {n.v('bandit.S2.diff.TSCTX_minus_TS.REG_oracle', 1)}; VAL {n.v('bandit.S2.diff.TSCTX_minus_TS.VAL')}")
        add(f"- S2, TS_PURE − TS_DEPLOYED: REG_fixed {n.v('bandit.S2.diff.TSPURE_minus_TS.REG_fixed', 1)} (the 50% random share is the price of logged propensities)")
        add("")
        if "field" in num:
            add("### Field-study replica")
            add("")
            add("| N | ID90 S1 | ID90 S2 | ID90 S3 | FID90 S0 |")
            add("|---|---|---|---|---|")
            for key in [k for k in num["field"] if k.startswith("N")]:
                add(f"| {key[1:]} | {n.v(f'field.{key}.S1.ID90')} | {n.v(f'field.{key}.S2.ID90')} | {n.v(f'field.{key}.S3.ID90')} | {n.v(f'field.{key}.S0.FID90')} |")
            add("")
            add(f"Runs per cell: {n.v('field.runs_per_cell')}. Mistakes per learner (N = 50, S2): {n.v('field.N50.S2.mistakes_per_learner', 2)}.")
            add("")

    # ---------- RQ3 ----------
    if "pipeline" in num:
        add("## RQ3 — Closed-loop pipeline (scenario S2)")
        add("")
        add("| Condition | TIB | FAS | RTS | CHURN | Δθ (model output) |")
        add("|---|---|---|---|---|---|")
        for c in ["C1", "C2", "C3", "C4", "C5"]:
            add(f"| {c} | {n.v(f'pipeline.{c}.TIB')} | {n.v(f'pipeline.{c}.FAS')} | {n.v(f'pipeline.{c}.RTS')} | {n.v(f'pipeline.{c}.CHURN')} | {n.v(f'pipeline.{c}.delta_theta', 2)} |")
        add("")
        add("Descriptive (no prediction): C2 − C1")
        add("")
        for m in ["TIB", "FRUS", "BORE", "CHURN", "FAS"]:
            add(f"- {m}: {n.v(f'pipeline.diff.C2_minus_C1.{m}')}")
        add("")
        if "activity" in num:
            add("Activity matrix (Fig H; condition C4, seeds 1–5): share of the 200 planned task slots per learner that ended as")
            add("")
            for k in ["correct", "recovered", "failed", "dont_know", "quit", "absent", "churned"]:
                add(f"- {k}: {n.v(f'activity.{k}.share')}")
            add("")
        add(f"Bandit inside the loop: RTS C4 − C3 {n.v('pipeline.diff.C4_minus_C3.RTS')}; C5 − C4 {n.v('pipeline.diff.C5_minus_C4.RTS')}.")
        add("")

    # ---------- robustness ----------
    if "robustness" in num:
        add("## Robustness (EXP-S)")
        add("")
        for key in ["K1", "K2", "K3", "K4"]:
            add(f"- {key} holds in {n.v(f'robustness.{key}.holds')} of {n.v(f'robustness.{key}.of')} settings.")
        add("")

    # ---------- calibration ----------
    if "calibration" in num:
        add("## Calibration (EXP-CAL)")
        add("")
        for t in ["warmup", "easy", "hard"]:
            add(f"- Tier {t}: delta {n.v(f'calibration.tiers.{t}.delta')}, mean success {n.v(f'calibration.tiers.{t}.achieved')} "
                f"(target {n.v(f'calibration.tiers.{t}.target', 2)}; reachable: {n.v(f'calibration.tiers.{t}.reachable')})")
        add(f"- Static plausibility run: churn {n.v('calibration.plausibility.churn_by_last_session.value')}; "
            f"\"don't know\" rate {n.v('calibration.plausibility.dont_know_rate.value')}; "
            f"median learner success between {n.v('calibration.plausibility.median_learner_success_per_session.min', 2)} and {n.v('calibration.plausibility.median_learner_success_per_session.max', 2)}; "
            f"field replica: {n.v('calibration.plausibility.field_replica_mistakes_per_learner.value', 2)} wrong first answers per learner")
        add("")

    # ---------- figures and tables ----------
    add("## Figures (caption drafts)")
    add("")
    for f in figs:
        add(f"**{f['id']}** (`{f['paths'][0]}`). {f['caption']}")
        add("")
    add("## Tables")
    add("")
    for md, caption in tabs:
        add(f"**{caption}**")
        add("")
        add(md)
    add("## Limitations to state in the paper")
    add("")
    add("1. Learners are synthetic. Engagement dynamics and learning increments are stylised; the sensitivity analysis checks that conclusions do not hinge on them, but cannot show that real learners behave this way.")
    add("2. Rewards, XP and explanations have no modelled effect on learners. The simulation evaluates properties of the explanations, not their effect on trust or understanding.")
    add("3. The grader is perfect by default; grader error is examined only in EXP-S.")
    add("4. Bandit updates are immediate; parallel classroom sessions are not modelled.")
    add("5. Results describe algorithmic behaviour, not learning outcomes. Effects on learners require the planned user study.")
    add("")
    SUMMARY.mkdir(parents=True, exist_ok=True)
    (SUMMARY / "RESULTS.md").write_text("\n".join(L))
